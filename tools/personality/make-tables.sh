#!/bin/bash
# Regenerates docs/personality-freebsd-syscalls.md and docs/personality-macos-syscalls.md.
#   wsl -d Ubuntu-20.04 -u root -e bash /mnt/e/os-11/tools/personality/make-tables.sh
# Inputs (see docs/personality-design.md, appendix): FreeBSD syscalls.master and the extracted
# base root; XNU's syscalls.master and Darling's bsd_syscall_table.c.
set -euo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
DOCS=$(cd "$HERE/../../docs" && pwd)
REF=${REF:-/opt/g11dl/ref}
FROOT=${FROOT:-/opt/g11work/freebsd-15.1/root}
DTABLE=${DTABLE:-/opt/g11root/src/darling/src/external/xnu/darling/src/libsystem_kernel/emulation/src/xnu_syscall/bsd/bsd_syscall_table.c}
{
cat <<'H'
# FreeBSD/amd64 system calls against Hydra's Linux layer

Generated by `tools/personality/fbsd_syscalls.py` (Group 11, 2026-11-18) from FreeBSD
15.1-RELEASE's `sys/kern/syscalls.master` (live `STD`/`NOSTD` entries only) and the
extracted `base.txz`. Explained in [personality-design.md](personality-design.md), section 4.

- **Class:** D = maps directly onto an existing Linux-layer operation (errno translation
  only); T = same operation with a layout, flag or constant translation; N = new; S = safe to
  stub at first.
- **Users:** how many ELF files of the FreeBSD 15.1 base system (27,172 files) import the
  call's C-library symbol: a rough measure of how much it matters. 0 means only static
  programs, `syscall(2)` or nothing in base use it.
- Every class also gets the errno translation and the carry-flag result convention
  (design section 2.4).

H
python3 -I "$HERE/fbsd_syscalls.py" "$REF/fbsd-syscalls.master" "$FROOT"
} > "$DOCS/personality-freebsd-syscalls.md"
{
cat <<'H'
# macOS (XNU) BSD system calls against the BSD core

Generated by `tools/personality/xnu_syscalls.py` (Group 11, 2026-11-18) from XNU
`xnu-12377.121.6` (macOS 26) `bsd/kern/syscalls.master` (without `nosys`/`enosys`) and
Darling's `bsd_syscall_table.c` at 2649752. Explained in
[personality-design.md](personality-design.md), section 5.

- **Class:** F = the same operation as the FreeBSD front end (shared BSD-core code, other
  number); T = macOS layout or constant differs from FreeBSD's; N = macOS-only; M = goes to
  mach-server; S = safe to stub at first.
- **Darling:** "yes" if Darling implements the call today: a measure of what real Mac
  programs need.
- On x86_64 these are called with `rax = 0x2000000 | number` (class 2); Mach traps (class 1)
  are in the design document, section 5.2.

H
python3 -I "$HERE/xnu_syscalls.py" "$REF/xnu-syscalls.master" "$DTABLE"
} > "$DOCS/personality-macos-syscalls.md"
{
cat <<'H'
# errno maps: Hydra's internal numbers to FreeBSD and macOS

Generated by `tools/personality/errno_map.py` (Group 11, 2026-11-18) from Linux's
`asm-generic/errno*.h`, FreeBSD 15.1's `sys/sys/errno.h` and XNU `xnu-12377.121.6`'s
`bsd/sys/errno.h`. Used by the result encoder of the personality hook
([personality-design.md](personality-design.md), section 2.4): a failing call's internal
`-errno` becomes the personality's positive errno with the carry flag set. Linux names with
no BSD errno of the same name map to the closest meaning (shown as "as ...").

Note `EOPNOTSUPP`: Linux has one value (95, `ENOTSUP` is the same); FreeBSD has one (45);
macOS has two (`ENOTSUP` 45 for files, `EOPNOTSUPP` 102 for sockets). The macOS front end
returns the internal `512 + 45` where it means `ENOTSUP`.

H
python3 -I "$HERE/errno_map.py" "$REF/linux-errno.h" "$REF/fbsd-errno.h" "$REF/xnu-errno.h"
} > "$DOCS/personality-errno.md"
wc -l "$DOCS"/personality-*-syscalls.md "$DOCS/personality-errno.md"
