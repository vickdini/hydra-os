#[test]
fn run_chroot_owns_the_console_until_the_program_ends() {
    let _g = setup();
    fake::with(|s| s.next_tid = 500);
    fake::task(500, 2, Some(1 << 8));
    linux::run_chroot("/ubuntu", &["/bin/bash"], 1000, 1000);
    let log = fake::take_log();
    let i = |p: &str| log.iter().position(|l| l == p).unwrap_or_else(|| panic!("{} not in {:?}", p, log));
    assert!(i("attach 500 500") < i("detach"));
    assert!(fake::take_out().ends_with("[+] Linux process 500 exited with status 1.\n"));
    // Its exit status is taken: a second wait does not know it
    let w = linux::wait_foreground(TaskId(500));
    assert_eq!(w.known, 0);
    // A start that fails
    fake::with(|s| s.spawn_fail = Some("ENOENT"));
    linux::run_chroot("/ubuntu", &["/bin/nope"], 0, 0);
    assert!(fake::take_out().contains("[!] linux chroot: ENOENT"));
}

#[test]
fn run_starts_programs_as_the_console_user() {
    let _g = setup();
    // Usage errors
    assert_eq!(linux::run(RUN_CHROOT, b"/ubuntu", 0, 0).unwrap_err(), "usage: root directory and program");
    assert_eq!(linux::run(RUN_CHROOT, b"\0/bin/sh", 0, 0).unwrap_err(), "usage: root directory and program");
    assert_eq!(linux::run(RUN_CHROOT, b"/ubuntu\0", 0, 0).unwrap_err(), "usage: root directory and program");
    assert_eq!(linux::run(RUN_FILE, b"", 0, 0).unwrap_err(), "no program given");
    assert_eq!(linux::run(RUN_FILE, b"ghost", 0, 0).unwrap_err(), "cannot read the program from the pool");
    assert_eq!(linux::run(7, b"x", 0, 0).unwrap_err(), "unknown kind of program");
    // A chroot program in the background
    let r = linux::run(RUN_CHROOT, b"/ubuntu\0/bin/ls\0-la", 1000, 1000).unwrap();
    assert_eq!((r.uid, r.gid, r.size), (1000, 1000, 0));
    assert!(fake::logged("spawn_chroot /ubuntu /bin/ls [\"/bin/ls\", \"-la\"] 1000 1000"));
    assert!(!fake::logged("attach"));
    // A program of the pool found as /bin/<name>.elf, in the foreground
    fake::file("/bin/hello.elf", b"\x7fELF-hello");
    let r = linux::run(RUN_FILE | RUN_FOREGROUND, b"hello\0x", 0, 0).unwrap();
    assert_eq!((r.size, name_str(&r.path)), (10, "/bin/hello.elf"));
    assert!(fake::logged("spawn_linux_elf linux_app 10 [\"/bin/hello.elf\", \"x\"] 0 0"));
    assert!(fake::logged(&format!("attach {} {}", r.pid, r.pid)));
    // Only one owns the console
    assert_eq!(linux::run(RUN_FILE | RUN_FOREGROUND, b"hello", 0, 0).unwrap_err(), "another Linux program owns the console");
    assert!(linux::wait(r.pid + 1).is_none());
    let w = linux::wait(r.pid).unwrap();
    assert_eq!((w.known, w.status), (1, 0));
    assert!(linux::wait(r.pid).is_none());
    // A spawn failure
    fake::with(|s| s.spawn_fail = Some("bad ELF"));
    assert_eq!(linux::run(RUN_FILE, b"/bin/hello.elf", 0, 0).unwrap_err(), "bad ELF");
}

#[test]
fn programs_are_looked_up_in_bin() {
    let _g = setup();
    fake::file("/bin/tool", b"T1");
    fake::file("/opt/abs", b"A");
    fake::file("/bin/empty", b"");
    fake::file("/bin/empty.elf", b"E");
    assert_eq!(name_str(&linux::run(RUN_FILE, b"tool", 0, 0).unwrap().path), "/bin/tool");
    assert_eq!(name_str(&linux::run(RUN_FILE, b"/opt/abs", 0, 0).unwrap().path), "/opt/abs");
    // An absolute path is only itself
    assert!(linux::run(RUN_FILE, b"/tool", 0, 0).is_err());
    // An empty file is skipped
    assert_eq!(name_str(&linux::run(RUN_FILE, b"empty", 0, 0).unwrap().path), "/bin/empty.elf");
    // A name ending in .elf is not given a second one
    assert!(linux::run(RUN_FILE, b"x.elf", 0, 0).is_err());
    fake::with(|s| s.fs_fail = Some("io"));
    assert!(linux::run(RUN_FILE, b"tool", 0, 0).is_err());
}

#[test]
fn self_test_report() {
    let _g = setup();
    fake::with(|s| s.msrs.insert(0xC000_0100, 0x1234));
    linux::self_test();
    let out = fake::take_out();
    assert!(out.contains("[+] sys_uname: Linux 6.8.0h"));
    assert!(out.contains("[+] /proc/version: Linux version 6.8.0-hydra (host test)"));
    assert!(out.contains("[+] /dev/urandom: [a0, a1, a2, a3, a4, a5, a6, a7]"));
    assert!(out.contains("MSR 0xC0000100 read/write verified"));
    assert!(out.ends_with("[+] Linux ABI self-tests completed successfully.\n"));
    // The caller's FS base is put back
    assert_eq!(fake::with(|s| s.msrs[&0xC000_0100]), 0x1234);
    // A CPU that drops the write
    fake::with(|s| s.msr_stuck = true);
    linux::self_test();
    assert!(fake::take_out().contains("[!] arch_prctl MSR test failed (mismatch: 0x1234)"));
}

#[test]
fn tracing() {
    let _g = setup();
    linux::trace(true, "firefox");
    assert!(k::compat::linux::TRACE_SYSCALLS.load(core::sync::atomic::Ordering::Relaxed));
    assert_eq!(k::compat::linux::TRACE_FILTER.lock().as_str(), "firefox");
    linux::trace(false, "");
    assert!(!k::compat::linux::TRACE_SYSCALLS.load(core::sync::atomic::Ordering::Relaxed));
}

#[test]
fn the_profiler() {
    use core::sync::atomic::Ordering::Relaxed;
    use k::compat::linux::prof;
    let _g = setup();
    assert!(linux::prof(&[PROF_ON, 0, 0, 0], ""));
    assert!(prof::ON.load(Relaxed));
    assert!(linux::prof(&[PROF_OFF, 0, 0, 0], ""));
    assert!(!prof::ON.load(Relaxed));
    assert!(linux::prof(&[PROF_RESET, 0, 0, 0], ""));
    assert!(linux::prof(&[PROF_SHOW, 15, 0, 0], ""));
    assert!(linux::prof(&[PROF_TUNE, 0, 1, 0], ""));
    assert!(k::arch::smp::DEFER_KICKS.load(Relaxed));
    assert!(linux::prof(&[PROF_TUNE, 1, 250, 0], ""));
    assert_eq!(k::arch::smp::IDLE_POLL_NS.load(Relaxed), 250_000);
    assert!(linux::prof(&[PROF_TUNE, 2, 0, 0], ""));
    assert!(linux::prof(&[PROF_TUNE, 0, 0, 0], ""));
    assert!(!k::arch::smp::DEFER_KICKS.load(Relaxed));
    assert!(linux::prof(&[PROF_WAITS, 40, 0, 0], ""));
    assert_eq!(prof::SLOW_MS.load(Relaxed), 40);
    assert!(linux::prof(&[PROF_WAITS_SHOW, 0, 0, 0], ""));
    fake::with(|s| s.named.insert("kwin".into(), 77));
    assert!(linux::prof(&[PROF_SAMPLE, 1, 0, 0], "kwin"));
    assert!(linux::prof(&[PROF_SAMPLE, 0, 0, 0], "*"));
    assert!(!linux::prof(&[PROF_SAMPLE, 0, 0, 0], "nothing"));
    assert!(linux::prof(&[PROF_SAMPLE_STOP, 0, 0, 0], ""));
    assert!(linux::prof(&[PROF_SAMPLE_SHOW, 5, 0, 0], ""));
    assert!(!linux::prof(&[99, 0, 0, 0], ""));
    assert_eq!(
        fake::take_log(),
        vec!["prof_reset", "prof_reset", "prof_show 15", "prof_slow_show", "sample_start 77 true", &format!("sample_start {} false", u64::MAX), "sample_start 0 false", "sample_show 5"]
    );
    let out = fake::take_out();
    assert!(out.contains("[+] Linux profile reset and started\n[+] Linux profile stopped\n"));
    assert!(out.contains("[+] kick deferral on, idle poll 0 us\n[+] kick deferral on, idle poll 250 us\n[+] kick deferral on, idle poll 250 us\n[+] kick deferral off, idle poll 250 us\n"));
    assert!(out.contains("[+] logging calls of 40 ms or more\n"));
    assert!(out.contains("[+] sampling task 77 (kwin)\n"));
    assert!(out.contains("[!] no task named nothing\n"));
}

