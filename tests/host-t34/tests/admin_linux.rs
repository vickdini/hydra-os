    let _g = setup();
    fake::file("/ubuntu/usr/libexec/hydra-session", b"x");
    fake::file("/ubuntu/usr/bin/sddm", b"x");
    fake::file("/ubuntu/usr/bin/startplasma-wayland", b"x");
