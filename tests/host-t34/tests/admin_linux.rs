#[test]
fn a_root_is_prepared_before_its_program_starts() {
    let _g = setup();
    // The lease's DNS server goes into empty network files
    net_server(5);
    iface_up([10, 0, 2, 15], [10, 0, 2, 3]);
    fake::file("/ubuntu/etc/resolv.conf", b"");
    fake::file("/ubuntu/etc/hosts", b"127.0.0.1 keep-me\n");
    let id = linux::spawn_in_root("/ubuntu/", &["/bin/bash", "-l"], 1000, 1000).unwrap();
    assert_eq!(fake::with(|s| s.files.get("/ubuntu/etc/resolv.conf").cloned()).unwrap(), b"# Generated by Hydra from the DHCP lease\nnameserver 10.0.2.3\n".to_vec());
    // A file with content is left alone
    assert_eq!(fake::with(|s| s.files.get("/ubuntu/etc/hosts").cloned()).unwrap(), b"127.0.0.1 keep-me\n".to_vec());
    let log = fake::take_log();
    let i = |p: &str| log.iter().position(|l| l.starts_with(p)).unwrap_or_else(|| panic!("{} not in {:?}", p, log));
    // /run/user stays searchable, /run/user/1000 is the user's alone
    assert!(log.contains(&"mkdir_all /ubuntu/run/user".to_string()));
    assert!(log.contains(&"setattr Some(\"755\") None None".to_string()));
    assert!(log.contains(&"mkdir_all /ubuntu/run/user/1000".to_string()));
    assert!(log.contains(&"setattr Some(\"700\") Some(1000) Some(1000)".to_string()));
    assert!(i("devices /ubuntu/") < i("spawn_chroot /ubuntu/ /bin/bash [\"/bin/bash\", \"-l\"] 1000 1000"));
    assert!(id.0 >= 100);
}

#[test]
fn network_files_without_a_lease() {
    let _g = setup();
    // No DNS server: only hosts is written (a missing file counts as empty)
    k::admin::linux::spawn_in_root("/r", &["/bin/sh"], 0, 0).unwrap();
    assert!(fake::with(|s| s.files.get("/r/etc/resolv.conf").is_none()));
    let hosts = fake::with(|s| s.files.get("/r/etc/hosts").cloned()).unwrap();
    assert!(String::from_utf8(hosts).unwrap().starts_with("127.0.0.1\tlocalhost\n127.0.1.1\thydra\n"));
    // A symbolic link, or a directory, is left alone
    fake::file("/s/etc/hosts", b"symlink:/run/hosts");
    net_server(5);
    iface_up([10, 0, 2, 15], [1, 1, 1, 1]);
    fake::dir("/s/etc/resolv.conf");
    k::admin::linux::spawn_in_root("/s", &["/bin/sh"], 0, 0).unwrap();
    assert_eq!(fake::with(|s| s.files.get("/s/etc/hosts").cloned()).unwrap(), b"symlink:/run/hosts".to_vec());
    assert!(fake::with(|s| s.files.get("/s/etc/resolv.conf").is_none()));
    assert!(!fake::logged("write /s/"));
}

