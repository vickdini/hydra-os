    linux::plasma("/ubuntu", true);
    let out = fake::take_out();
    assert!(out.contains("[*] Starting KDE Plasma..."));
    assert!(fake::logged("spawn_chroot /ubuntu /bin/sh [\"/bin/sh\", \"/usr/libexec/hydra-session\", \"env\", \"KWIN_COMPOSE=Q\", \"XCURSOR_THEME=breeze_cursors\", \"dbus-run-session\", \"startplasma-wayland\"] 0 0"));
